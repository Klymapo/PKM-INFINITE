import assert from 'node:assert/strict';
import * as W from '../../app/js/world.js';
import {newGame,G} from '../../app/js/state.js';
import {C} from '../../app/js/content.js';
const RealDate=Date;
globalThis.Date=class extends RealDate {constructor(...args){super(...(args.length?args:[2026,10,4,13,0,0]));}};
newGame({name:'Test'});C.events=[];
const loc={id:'horario_test',spots:[{action:{explore:true}},{action:{explore:'water'}}],encounters:{grass:[{sp:'rattata',lv:5,time:'day'},{sp:'zubat',lv:6,time:'night'},{sp:'pidgey',lv:7,time:'morning'},{sp:'magikarp',lv:5},{sp:'gastly',lv:5,time:'night',cond:false}],water:[{sp:'chinchou',lv:8,time:'night'}]}};
const guide=l=>W.zoneGuideEncounters?W.zoneGuideEncounters(l):Object.fromEntries(W.dexnavTerrains(l).map(t=>[t,W.encounterTable(l,t)]));
assert.ok(guide(loc).grass.some(e=>e.sp==='zubat'),'la guía de día debe conservar los nocturnos');
assert.ok(guide(loc).grass.some(e=>e.sp==='pidgey'),'la guía debe conservar los de la mañana');
assert.ok(guide(loc).water.some(e=>e.sp==='chinchou'),'terreno solo nocturno visible en la guía');
assert.ok(!guide(loc).grass.some(e=>e.sp==='gastly'),'seguir respetando condiciones de historia');
assert.deepEqual(W.encounterTable(loc,'grass').map(e=>e.sp),['rattata','magikarp'],'el rastreo sigue usando la hora actual');
assert.deepEqual(W.dexnavTerrains(loc),['grass'],'no rastrear en agua nocturna durante el día');
assert.equal(W.encounterOdds(loc,'grass','noche').zubat,0.5);
assert.equal(W.encounterOdds(loc,'grass','dia').zubat,undefined);
assert.equal(W.encounterOdds(loc,'grass','manana').pidgey,1/3);
C.events=[{id:'test',from:'01-01',to:'12-31',encounters:{horario_test:{grass:[{sp:'hoothoot',lv:9,time:'night'}]}}}];
assert.ok(guide(loc).grass.some(e=>e.sp==='hoothoot'),'conservar eventos activos en todos los horarios');
assert.ok(!W.encounterTable(loc,'grass').some(e=>e.sp==='hoothoot'));
assert.deepEqual(guide({id:'inside',parent:loc.id,spots:[]}),{},'no heredar tablas de otro lugar');
const route={id:'route',route:{terrain:'grass',tramos:{2:[{terrain:'water'}]},encounters:loc.encounters}};G.route={id:'route',pos:2};
assert.deepEqual(Object.keys(guide(route)),['water'],'conservar el terreno del tramo actual');
console.log('Guía completa por horario; rastreo actual, probabilidades, condiciones, eventos y terreno: OK');
