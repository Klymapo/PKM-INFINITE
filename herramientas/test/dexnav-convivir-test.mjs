import assert from 'node:assert/strict';
import { convivir } from '../../app/js/convivir.js';
import { dexnavTerrains } from '../../app/js/world.js';
import { newGame, G } from '../../app/js/state.js';
import { C } from '../../app/js/content.js';
const d = new Date(2026, 10, 4, 12), next = new Date(2026, 10, 5, 12);
const p = { happy: 210, item:'soothebell', ball:'luxuryball' };
assert.equal(convivir(p,d).gained,15);
assert.equal(p.happy,225);
assert.equal(convivir(p,d).gained,0);
const saved = JSON.parse(JSON.stringify(p)); saved.sp = 'evolved';
assert.equal(convivir(saved,d).gained,0);
assert.equal(convivir(saved,next).gained,15);
assert.equal(convivir(saved,d).gained,0);
assert.equal(convivir({happy:250},d).gained,5);
assert.equal(convivir({happy:255},d).gained,0);
assert.equal(convivir({happy:0},d).gained,15);
assert.equal(convivir({happy:0},d).gained,15);
newGame({name:'Test'}); C.events = [];
const grass = [{sp:'rattata',lv:5}], water = [{sp:'magikarp',lv:5}];
const city = {id:'city',encounters:{grass,water},spots:[{action:{explore:true}},{action:{explore:'water'}}]};
assert.deepEqual(dexnavTerrains(city),['grass','water']);
assert.deepEqual(dexnavTerrains({id:'interior',parent:'city',spots:[]}),[]);
assert.deepEqual(dexnavTerrains({...city,spots:[{action:{training:{wild:grass}}}]}),[]);
assert.deepEqual(dexnavTerrains({...city,spots:[{cond:false,action:{explore:true}}]}),[]);
assert.deepEqual(dexnavTerrains({...city,encounters:{grass:[{sp:'rattata',lv:5,cond:false}]},spots:[{action:{explore:true}}]}),[]);
const route = {id:'route',route:{terrain:'grass',tramos:{2:[{terrain:'water'}]},encounters:{grass,water}}};
G.route={id:'route',pos:2}; assert.deepEqual(dexnavTerrains(route),['water']);
G.route={id:'other',pos:2}; assert.deepEqual(dexnavTerrains(route),['grass']);
C.events=[{id:'test',from:'01-01',to:'12-31',encounters:{city:{grass}}}];
assert.deepEqual(dexnavTerrains({...city,encounters:{},spots:[{action:{explore:true}}]}),['grass']);
console.log('DexNav local, condiciones, eventos y amistad diaria: OK');
