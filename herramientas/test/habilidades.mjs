import assert from 'node:assert/strict';
import { loadDataNode } from './node-env.mjs';
import { abilityOptions, changeAbility } from '../../app/js/habilidades.js';
import { toSimSet, createPokemon } from '../../app/js/pokemon.js';
loadDataNode();
const g = createPokemon('golisopod', { level: 40 });
assert.deepEqual(abilityOptions(g, 'abilitycapsule'), []);
assert.deepEqual(abilityOptions(g, 'abilitypatch'), []);
assert.equal(changeAbility(g, 'custom', 'wonderguard'), false);
assert.equal(changeAbility(g, 'custom', 'shellarmor'), true);
assert.equal(g.abilityCustom, true);
assert.equal(JSON.parse(JSON.stringify(g)).abil, 'shellarmor');
assert.equal(toSimSet(g).ability, 'shellarmor');
assert.equal(changeAbility(g, 'custom', 'shellarmor'), false);
assert.equal(changeAbility(g, 'custom', 'emergencyexit'), true);
assert.equal(g.abilityCustom, false);
const p = createPokemon('ralts', { level: 20, abilitySlot: '0' });
assert.equal(changeAbility(p, 'abilitycapsule', 'trace'), true);
assert.equal(p.abilSlot, '1');
assert.equal(changeAbility(p, 'abilitypatch', 'telepathy'), true);
assert.equal(p.abilSlot, 'H');
assert.deepEqual(abilityOptions(p, 'abilitycapsule'), []);
assert.equal(changeAbility(p, 'custom', 'shellarmor'), false);
const restored = JSON.parse(JSON.stringify(g));
assert.equal(restored.abil, 'emergencyexit');
console.log('Habilidades: opciones, validación, slots y simulador OK');
