// Prueba de la guardería: niveles por tiempo, compatibilidad, huevo, eclosión. Uso: node herramientas/test/guarderia-test.mjs
import { loadDataNode } from './node-env.mjs';
loadDataNode();
const mod = await import('../../app/content/index.js');
const { registerBlock, C } = await import('../../app/js/content.js');
if (!C.blocks.length) for (const b of mod.BLOCKS) registerBlock(b);
const S = await import('../../app/js/state.js');
const { createPokemon } = await import('../../app/js/pokemon.js');
const DC = await import('../../app/js/guarderia.js');
const g = S.newGame({ name: 'Test', pron: 'el' }); S.setG(g);
g.vars.cap = 30; g.player.money = 5000;
const a = createPokemon('pikachu', { level: 10, gender: 'M' }), b = createPokemon('pikachu', { level: 12, gender: 'F' }), c = createPokemon('mew', { level: 10 });
g.party = [a, b, c, createPokemon('ditto', { level: 5 })];
let fails = 0; const ok = (cond, msg) => { if (!cond) { fails++; console.log('✖', msg); } else console.log('✔', msg); };
ok(DC.baseOf('gallade') === 'ralts' && DC.baseOf('alakazam') === 'abra' && DC.baseOf('pikachu') === 'pichu', 'baseOf sigue la cadena hasta la base');
ok(!DC.compatible(a, c).ok, 'Mew no puede tener huevos');
ok(DC.compatible(a, b).ok && DC.compatible(a, b).parent === b, 'macho + hembra del mismo grupo: compatible, la madre manda');
ok(DC.compatible(a, g.party[3]).ok, 'Ditto + cualquiera: compatible');
ok(DC.deposit(a) === null && DC.deposit(b) === null && g.party.length === 2, 'dejar dos');
ok(DC.deposit(c) !== null, 'no cabe un tercero');
const t0 = Date.now(); DC.state().last = t0;
let r = DC.tick(t0 + 7 * DC.HOUR, g, () => 0.99);
ok(r.leveled.length === 2 && a.lv === 12 && b.lv === 14, '7 h → +2 niveles cada uno');
ok(!r.egg, 'sin suerte no hay huevo');
r = DC.tick(t0 + 8 * DC.HOUR, g, () => 0.0);
ok(r.egg && DC.state().egg?.sp === 'pichu', 'con suerte hay huevo y es de la especie base de la madre');
for (let i = 0; i < DC.EGG_BATTLES - 1; i++) ok(DC.battleTick() === false || i === DC.EGG_BATTLES - 2, 'incubando ' + (i + 1));
ok(DC.battleTick() === true && DC.eggReady(), 'tras 12 combates eclosiona');
const baby = DC.hatch(g, 'trigal');
ok(baby && baby.sp === 'pichu' && baby.lv === 1 && g.party.includes(baby) && !DC.state().egg, 'eclosión: Pichu nv 1 al equipo');
r = DC.tick(t0 + 200 * DC.HOUR, g, () => 0.99);
ok(a.lv === 30 && b.lv === 30, 'no pasa del tope de nivel');
const cost = DC.withdrawCost(a);
ok(cost === 100 * (30 - 10), 'coste ₽100 por nivel ganado: ' + cost);
ok(DC.withdraw(a) === null && g.party.includes(a) && g.player.money === 5000 - cost, 'recoger paga y vuelve al equipo');
console.log(fails ? `\n${fails} fallos` : '\nTodo bien.');
process.exit(fails ? 1 : 0);
